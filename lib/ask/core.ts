// The automatic answer pipeline (plan section 7), after two Codex code reviews.
// This file holds the logic only; lib/ask/pipeline.ts plugs in the real AI and Quran source.
// Because everything comes in through `deps`, tests can run it with a fake AI (tests/pipeline.test.ts).
//
// 1. frame: the AI turns the question into a strictly validated question type, exact requested
//    points, qualifiers and short multilingual search phrases. No visitor instructions survive.
// 2. personal questions (AI or code rule) stop here: the visitor is sent to a scholar.
// 3. retrieve: direct references first, then a larger candidate set from Quran Foundation search.
// 4. select evidence: a different model sees the structured question, candidates and surrounding
//    context. Code seals only direct, context-safe evidence that covers every requested point.
// 5. draft: the writer sees only that sealed package, never rejected passages or the raw question.
// 6. code checks every claim, citation and requested point. Any failure refuses the whole answer.
// 7. final screening: the independent model checks support, coverage, context and fairness.
// 8. the website shows verses from source data, never Quran text generated by AI.

