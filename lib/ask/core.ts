// The selector judges meaning from the Arabic and the English translation; the German copy is
// left out to keep its reading load (and time) down now that long hadith texts are candidates.
function selectionSource(candidate: PassageForSelection, namedByVisitor: Set<string>) {
  const text = (s: Source) => sourceJson(s, "en");
  const contextText = (verse: Verse) => {
    const { id: _id, ...withoutId } = text(verseSource(verse));
    return withoutId;
  };
  return {
    source: text(candidate.source),
    ...(namedByVisitor.has(candidate.id) ? { named_by_visitor: true } : {}),
    // Context stays visible for safety, but has no id so it cannot be mistaken for a selectable source.
    surrounding_context: candidate.context.map(contextText),
  };
}

function sealedPackageJson(evidence: EvidencePackage, language: Locale, forWriter = false, includeContext = false) {
  return {
    question: evidence.question,
    passages: evidence.passages.map((passage) => {
      const source = sourceJson(passage.source, language);
      const context = includeContext
        ? { surrounding_context: passage.context.map((verse) => sourceJson(verseSource(verse), language)) }
        : {};
      // The writer works from the approved translations only, in every language: this keeps it from
      // retyping Arabic Quran or hadith text and keeps its input short. Code checks and final
      // screening still compare every claim against the Arabic.
      if (forWriter && passage.source.kind !== "scholar") {
        const { arabic: _arabic, ...withoutArabic } = source;
        return { ...withoutArabic, supported_requirement_ids: passage.requirementIds, ...context };
      }
      return { ...source, supported_requirement_ids: passage.requirementIds, ...context };
    }),
  };
}

// Resolves with the hadith, or with an empty list if the search fails or is too slow.
async function hadithCandidates(
  deps: PipelineDeps,
  queries: Partial<Record<Locale, string[]>>,
): Promise<{ hadith: Hadith[]; problem: string | null }> {
  if (!deps.searchHadith) return { hadith: [], problem: null };
  let timer: ReturnType<typeof setTimeout> | undefined;
  const timeout = new Promise<"timeout">((resolve) => {
    timer = setTimeout(() => resolve("timeout"), deps.hadithTimeoutMs ?? HADITH_TIMEOUT_MS);
  });
  try {
    const result = await Promise.race([deps.searchHadith(queries), timeout]);
    if (result === "timeout") return { hadith: [], problem: "hadith_search_timeout" };
    const allowed = result.filter(hadithAllowed);
    return { hadith: allowed, problem: allowed.length < result.length ? "hadith_dropped_by_rules" : null };
  } catch {
    return { hadith: [], problem: "hadith_search_failed" };
  } finally {
    clearTimeout(timer);
  }
}

// Scholar quotes are an extra source too: failure or slowness means the answer continues without them.
async function scholarCandidates(
  deps: PipelineDeps,
  arabicPhrases: string[],
): Promise<{ quotes: ScholarQuote[]; problem: string | null }> {
  if (!deps.searchScholars || arabicPhrases.length === 0) return { quotes: [], problem: null };
  let timer: ReturnType<typeof setTimeout> | undefined;
  const timeout = new Promise<"timeout">((resolve) => {
    timer = setTimeout(() => resolve("timeout"), deps.hadithTimeoutMs ?? HADITH_TIMEOUT_MS);
  });
  try {
    const result = await Promise.race([deps.searchScholars(arabicPhrases), timeout]);
    if (result === "timeout") return { quotes: [], problem: "scholar_search_timeout" };
    const allowed = result.filter(scholarQuoteAllowed);
    return { quotes: allowed, problem: allowed.length < result.length ? "scholar_dropped_by_rules" : null };
  } catch {
    return { quotes: [], problem: "scholar_search_failed" };
  } finally {
    clearTimeout(timer);
  }
}

// Videos never block or change an answer: on failure or timeout the answer simply has none.
async function videoCandidates(
  deps: PipelineDeps,
  arabicPhrases: string[],
): Promise<{ videos: VideoSuggestion[]; problem: string | null }> {
  if (!deps.searchVideos || arabicPhrases.length === 0) return { videos: [], problem: null };
  let timer: ReturnType<typeof setTimeout> | undefined;
  const timeout = new Promise<"timeout">((resolve) => {
    timer = setTimeout(() => resolve("timeout"), deps.hadithTimeoutMs ?? HADITH_TIMEOUT_MS);
  });
  try {
    const result = await Promise.race([deps.searchVideos(arabicPhrases), timeout]);
    if (result === "timeout") return { videos: [], problem: "video_search_timeout" };
    // Defence in depth: only the approved channels, whatever the search returned.
    const allowed = result.filter((v) => approvedChannelIds.has(v.channelId) && /^[A-Za-z0-9_-]{11}$/.test(v.youtubeId));
    return { videos: allowed.slice(0, MAX_VIDEO_CANDIDATES), problem: allowed.length < result.length ? "video_dropped_by_rules" : null };
  } catch {
    return { videos: [], problem: "video_search_failed" };
  } finally {
    clearTimeout(timer);
  }
}

async function relevantVideos(
  deps: PipelineDeps,
  requirements: { id: string; text: string }[],
  candidates: VideoSuggestion[],
  signal: AbortSignal,
): Promise<VideoSuggestion[]> {
  if (candidates.length === 0) return [];
  try {
    const output = await deps.verifier.generateJson({
      system: VIDEO_RELEVANCE_SYSTEM,
      prompt: JSON.stringify({
        requirements,
        titles: candidates.map((video, index) => ({ index, title: video.title, language: video.language })),
      }),
      maxOutputTokens: 512,
      thinking: "minimal",
      signal,
      schema: {
        type: "object",
        properties: {
          verdicts: { type: "array", items: { type: "string", enum: ["yes", "no"] } },
        },
        required: ["verdicts"],
      },
    }) as { verdicts?: unknown } | null;
    const verdicts = output?.verdicts;
    if (!Array.isArray(verdicts) || verdicts.length !== candidates.length) return [];
    if (!verdicts.every((verdict) => verdict === "yes" || verdict === "no")) return [];
    return candidates.filter((_, index) => verdicts[index] === "yes").slice(0, MAX_VIDEOS);
  } catch {
    return [];
  }
}

// ---------- the pipeline ----------
export async function runPipeline(question: string, uiLanguage: Locale, deps: PipelineDeps): Promise<AskResult> {
  // 50 s: the longest safe path (redraft, second screening or evidence audit) must fit on budget
  // models. The route allows 60 s, so the answer still returns before the server gives up.
  const signal = AbortSignal.timeout(deps.deadlineMs ?? 50_000);
  const started = Date.now();
  const step = (name: string) => deps.onStep?.(name, Date.now() - started);
  const refuse = (reason: string, language: Locale): AskResult => {
    deps.onRefuse?.(reason);
    return { status: "no_source", language };
  };

  // 1. Build a bounded question frame. Anything malformed or unknown is refused.
  const understandOnce = (correction?: string) => deps.writer.generateJson({
      system: UNDERSTAND_SYSTEM,
      prompt: JSON.stringify({
        visitor_text: question,
        ...(correction ? { correction } : {}),
      }),
      maxOutputTokens: 900,
      signal,
      schema: {
        type: "object",
        properties: {
          language: { type: "string", enum: ["ar", "en", "de"] },
          kind: { type: "string", enum: ["question", "personal", "greeting", "off_topic", "harmful"] },
          question_type: { type: "string", enum: [...QUESTION_TYPES] },
          subjects: words,
          requested_points: {
            type: "array",
            items: {
              type: "object",
              properties: {
                text: { type: "string" },
                facet: { type: "string", enum: [...ANSWER_FACETS] },
              },
              required: ["text", "facet"],
            },
          },
          qualifiers: words,
          search_queries_en: words,
          search_queries_de: words,
          search_queries_ar: words,
        },
        required: [
          "language",
          "kind",
          "question_type",
          "subjects",
          "requested_points",
          "qualifiers",
          "search_queries_en",
          "search_queries_de",
          "search_queries_ar",
        ],
      },
    });
  let frame = parseQuestionFrame(await understandOnce());
  const frameProblem = (candidate: typeof frame) => candidate
    ? (candidate.kind === "personal" && isGeneralGuidanceQuestion(question) ? "general_guidance_misclassified" : null)
      ?? questionFrameMismatch(question, candidate)
      ?? (candidate.language === "ar" && candidate.kind === "question" && (candidate.searchQueries.ar?.length ?? 0) === 0 ? "arabic_queries_missing" : null)
    : "invalid";
  if (frameProblem(frame)) {
    const retried = parseQuestionFrame(await understandOnce(
      `Correct the question frame against the original visitor wording. Problem: ${frameProblem(frame)}. Include every requested point, exclude points not asked, and distinguish the zakat amount due from its threshold. General conversion and repentance guidance is not a personal ruling. requested_points text must be short plain English, even when the visitor writes in Arabic or German. Every search_queries_ar phrase must be written in Arabic script.`,
    ));
    frame = retried;
  }
  step("frame");
  if (!frame || frameProblem(frame)) return refuse("question_frame_invalid", uiLanguage);
  if (frame.kind === "greeting" || frame.kind === "off_topic" || frame.kind === "harmful") {
    return { status: "out_of_scope", language: frame.language };
  }

  // 2. personal situations are never answered automatically
  if (frame.kind === "personal" || looksPersonal(question)) {
    deps.onRefuse?.("personal");
    return { status: "ask_scholar", language: frame.language };
  }
  const language = frame.language;

  // 3. Retrieve candidates. Search phrases improve recall but are never treated as evidence.
  const queries = buildSearchQueries(frame);
  const direct = directRefs(question);
  if (queries.length === 0 && direct.length === 0) return refuse("query_plan_empty", language);
  // Quran and hadith are searched at the same time. Hadith use the English phrases (plus the
  // English subject names) on the English list and the Arabic phrases on the Arabic list.
  const [found, hadithResult, scholarResult, videoResult] = await Promise.all([
    deps.search(queries, MAX_QURAN_CANDIDATES),
    hadithCandidates(deps, {
      en: [...(frame.searchQueries.en ?? []), ...frame.subjects],
      ar: frame.searchQueries.ar ?? [],
    }),
    scholarCandidates(deps, frame.searchQueries.ar ?? []),
    videoCandidates(deps, frame.searchQueries.ar ?? []),
  ]);
  if (videoResult.problem) deps.onRefuse?.(videoResult.problem); // reason code only; the answer continues
  if (scholarResult.problem) deps.onRefuse?.(scholarResult.problem); // reason code only; the answer continues
  step("search");
  if (hadithResult.problem) deps.onRefuse?.(hadithResult.problem); // reason code only; the answer continues
  const keys = [...new Set([...direct, ...found])].slice(0, MAX_QURAN_CANDIDATES);
  const verses = (await Promise.all(keys.map((k) => deps.getVerse(k))))
    .filter((v): v is Verse => !!v);
  const hadith = hadithResult.hadith.slice(0, MAX_HADITH_CANDIDATES);
  const quotes = scholarResult.quotes.slice(0, MAX_SCHOLAR_CANDIDATES);
  if (verses.length === 0 && hadith.length === 0 && quotes.length === 0) return refuse("search_empty", language);

  // 4. The independent model classifies every candidate with its own local context. Code seals
  // only direct, context-safe passages and requires evidence for every requested point.
  const candidates: PassageForSelection[] = [
    ...(await Promise.all(verses.map(async (verse) => ({
      id: `Q${verse.key}`,
      source: verseSource(verse),
      context: (await deps.neighbours(verse.key)).filter((near) => near.key !== verse.key),
    })))),
    ...hadith.map((h) => ({ id: h.id, source: { kind: "hadith", hadith: h } as Source, context: [] })),
    ...quotes.map((q) => ({ id: q.id, source: { kind: "scholar", quote: q } as Source, context: [] })),
  ];
  step("sources_fetched");
  const selected = await deps.verifier.generateJson({
    system: EVIDENCE_SYSTEM,
    prompt: JSON.stringify({
      question: {
        language: frame.language,
        question_type: frame.questionType,
        subjects: frame.subjects,
        requirements: frame.requirements,
        qualifiers: frame.qualifiers,
      },
      // Verses the visitor named by number or well-known name ("Ayat al-Kursi"), matched by code.
      candidates: candidates.map((c) => selectionSource(c, new Set(direct.map((key) => `Q${key}`)))),
    }),
    maxOutputTokens: 3072,
    thinking: "low",
    signal,
    schema: {
      type: "object",
      properties: {
        status: { type: "string", enum: ["ready", "insufficient", "ambiguous", "conflicting"] },
        coverage: { type: "string", enum: ["complete", "incomplete", "uncertain"] },
        conflict: { type: "string", enum: ["none", "present", "uncertain"] },
        assessments: {
          type: "array",
          items: {
            type: "object",
            properties: {
              source_id: { type: "string" },
              relevance: { type: "string", enum: ["direct", "partial", "context", "mention_only", "unrelated"] },
              supported_requirement_ids: {
                type: "array",
                items: { type: "string", enum: frame.requirements.map((requirement) => requirement.id) },
              },
              context_safe: { type: "string", enum: ["yes", "no", "unsure"] },
            },
            required: ["source_id", "relevance", "supported_requirement_ids", "context_safe"],
          },
        },
      },
      required: ["status", "coverage", "conflict", "assessments"],
    },
  });
  step(`selection(${candidates.length} candidates)`);
  const evidencePackage = parseEvidencePackage(selected, frame, candidates);
  if (!evidencePackage) return refuse("evidence_insufficient", language);
  // 5 + 6. The writer sees only the sealed package. Code verifies citations and requested-point coverage.
  const selectedSources = evidencePackage.passages.map((passage) => passage.source);
  const byId = new Map(selectedSources.map((s) => [sourceId(s), s]));
  const citable = selectedSources.map(asSource);
  const sourceRequirements = Object.fromEntries(
    evidencePackage.passages.map((passage) => [passage.id, passage.requirementIds]),
  );
  const requirementIds = frame.requirements.map((requirement) => requirement.id);
  const requirementReminder = frame.requirements.map((requirement) => `${requirement.id}: ${requirement.text}`).join("; ");
  const answerFrom = async (claims: Claim[], sourceOnly = false): Promise<AskResult> => {
    // Optional title checking starts only after the checked answer is complete, so it cannot
    // compete with selection, drafting or screening. Timeout and malformed output mean no videos.
    const videos = await relevantVideos(
      deps,
      frame.requirements.map(({ id, text }) => ({ id, text })),
      videoResult.videos,
      AbortSignal.any([signal, AbortSignal.timeout(VIDEO_RELEVANCE_TIMEOUT_MS)]),
    );
    const used = sourceOnly
      ? selectedSources
      : [...new Set(claims.flatMap((claim) => claim.refs))].map((id) => byId.get(id)!);
    // Verse refs are shown as "2:255"; hadith refs keep their id ("HE4196") and the page shows
    // the Bukhari/Muslim number from the evidence.
    const displayRef = (id: string) => (id.startsWith("Q") ? id.slice(1) : id);
    return {
      status: "answer",
      answer: {
        language,
        claims: claims.map((claim) => ({ text: claim.text, refs: claim.refs.map(displayRef) })),
        evidence: used.map((s) => toEvidence(s, language)),
        ...(sourceOnly ? { sourceOnly: true } : {}),
        attribution: { ...ATTRIBUTION },
        ...(used.some((s) => s.kind === "hadith") ? { hadithAttribution: { ...HADITH_ATTRIBUTION } } : {}),
        ...(videos.length > 0 ? { videos } : {}),
        model: deps.writer.id,
        verifier: deps.verifier.id,
      },
    };
  };
  // Source-only fallback: when the sealed package is sound but no AI wording survives the checks,
  // show only the exact approved passages. Allowed ONLY after wording failures (copying, quoting,
  // sentence/requirement shape) or failed claim screening, never when the writer itself says the
  // evidence is insufficient, returns malformed output or cites an unapproved source.
  // A second model (the writer's, not the selector's) must independently approve the package.
  const sourceOnlyFallback = async (reason: string, wordingFailure: boolean): Promise<AskResult> => {
    if (!wordingFailure) return refuse(reason, language);
    deps.onRefuse?.(`source_only_after_${reason}`); // reason code only; the audit decides what is shown
    const audit = await deps.writer.generateJson({
      system: EVIDENCE_AUDIT_SYSTEM,
      prompt: JSON.stringify({
        question: evidencePackage.question,
        evidence_package: sealedPackageJson(evidencePackage, language, false, true),
      }),
      maxOutputTokens: 800,
      signal,
      schema: {
        type: "object",
          properties: {
            requirement_verdicts: {
              type: "array",
              items: {
                type: "object",
                properties: {
                  requirement_id: { type: "string", enum: requirementIds },
                  verdict: { type: "string", enum: ["yes", "no", "unsure"] },
                },
                required: ["requirement_id", "verdict"],
              },
            },
            answers_question: { type: "string", enum: ["yes", "no", "unsure"] },
          covers_facets: { type: "string", enum: ["yes", "no", "unsure"] },
          fair_picture: { type: "string", enum: ["yes", "no", "unsure"] },
          context_preserved: { type: "string", enum: ["yes", "no", "unsure"] },
        },
        required: ["requirement_verdicts", "answers_question", "covers_facets", "fair_picture", "context_preserved"],
      },
    });
    if (!wholeAnswerOk(audit) || !requirementsCovered(audit, requirementIds)) return refuse(reason, language);
    return answerFrom([], true);
  };
  const draftOnce = async (correction?: string) =>
    parseDraft(
      await deps.writer.generateJson({
        system: DRAFT_SYSTEM,
        prompt: JSON.stringify({
          answer_language: LANGUAGE_NAMES[language],
          ...(language === "ar"
            ? { writing_rule: "Write every claim in Arabic script, in your own simple words. The English translation is only there to help you understand; do not copy the Arabic verse wording." }
            : {}),
          ...(correction ? { correction } : {}),
          evidence_package: sealedPackageJson(evidencePackage, language, true),
        }),
        maxOutputTokens: 1200,
        signal,
        schema: {
          type: "object",
          properties: {
            status: { type: "string", enum: ["answer", "no_answer"] },
            claims: {
              type: "array",
              items: {
                type: "object",
                properties: {
                  text: { type: "string" },
                  source_ids: words,
                  requirement_id: { type: "string", enum: requirementIds },
                },
                required: ["text", "source_ids", "requirement_id"],
              },
            },
          },
          required: ["status", "claims"],
        },
      }),
      citable,
      language,
      { requirements: frame.requirements, sourceRequirements },
    );
  let parsed = await draftOnce();
  step("draft");
  if (!parsed.ok && RETRYABLE.has(parsed.reason)) {
    parsed = await draftOnce(
      `The previous draft failed the code rule "${parsed.reason}". Use shorter, simpler wording, exactly one fact and one requirement_id per claim, and do not reproduce source wording. You must still cover every requested point: ${requirementReminder}.`,
    );
  }
  if (!parsed.ok) return sourceOnlyFallback(`draft_${parsed.reason}`, RETRYABLE.has(parsed.reason));

  // 7. Independent final screening of the answer against the sealed package.
  const screen = (claims: Claim[]) => deps.verifier.generateJson({
      system: SUPPORT_SYSTEM,
      prompt: JSON.stringify({
        answer_language: LANGUAGE_NAMES[language],
        question: evidencePackage.question,
        evidence_package: sealedPackageJson(evidencePackage, language, false, true),
        claims: claims.map((claim) => ({
          claim: claim.text,
          requirement_id: claim.requirementId,
          passages: claim.refs.map((id) => {
            const s = byId.get(id)!;
            return { type: s.kind, arabic: sourceArabic(s), translation_en: sourceTranslations(s).en };
          }),
        })),
      }),
      // The screening model thinks before answering, which uses up output space: give it room.
      maxOutputTokens: 2048,
      thinking: "low",
      signal,
      schema: {
        type: "object",
        properties: {
          verdicts: { type: "array", items: { type: "string", enum: ["supported", "not_supported", "unsure"] } },
          requirement_verdicts: {
            type: "array",
            items: {
              type: "object",
              properties: {
                requirement_id: { type: "string", enum: requirementIds },
                verdict: { type: "string", enum: ["yes", "no", "unsure"] },
              },
              required: ["requirement_id", "verdict"],
            },
          },
          answers_question: { type: "string", enum: ["yes", "no", "unsure"] },
          covers_facets: { type: "string", enum: ["yes", "no", "unsure"] },
          fair_picture: { type: "string", enum: ["yes", "no", "unsure"] },
          context_preserved: { type: "string", enum: ["yes", "no", "unsure"] },
        },
        required: ["verdicts", "requirement_verdicts", "answers_question", "covers_facets", "fair_picture", "context_preserved"],
      },
    });

  let verdicts = await screen(parsed.claims);
  step("screening");
  if (!verdicts) return refuse("screening_unreadable", language);
  if (!allSupported(verdicts, parsed.claims.length)
    || !wholeAnswerOk(verdicts)
    || !requirementsCovered(verdicts, requirementIds)) {
    const corrected = await draftOnce(
      `The previous wording failed independent screening. Use shorter, more literal wording with one explicit fact per claim and no implication or extra conclusion. You must still cover every requested point: ${requirementReminder}.`,
    );
    if (!corrected.ok) return sourceOnlyFallback(`screening_retry_${corrected.reason}`, RETRYABLE.has(corrected.reason));
    parsed = corrected;
    verdicts = await screen(parsed.claims);
    if (!verdicts) return refuse("screening_retry_unreadable", language);
  }
  if (!allSupported(verdicts, parsed.claims.length)) return sourceOnlyFallback("screening_claim", true);
  if (!wholeAnswerOk(verdicts) || !requirementsCovered(verdicts, requirementIds)) {
    return sourceOnlyFallback("screening_whole_answer", true);
  }

  // 8. Evidence shown to the visitor is exactly what the checked claims cite.
  return answerFrom(parsed.claims);
}
