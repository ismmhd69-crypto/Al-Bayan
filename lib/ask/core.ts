export type Evidence =
  | {
      kind: "quran";
      key: string; // "2:255"
      arabic: string;
      translation: string | null; // exactly as served; null for Arabic readers or if not showable
      translationName: string | null;
      url: string;
    }
  | {
      kind: "hadith";
      key: string; // "HE4196" (HadeethEnc id)
      collection: HadithCollection;
      numbers: { bukhari: number | null; muslim: number | null };
      gradeAr: string; // exactly as served
      attributionAr: string; // exactly as served
      arabic: string; // exactly as served
      translation: string | null; // exactly as served; null for Arabic readers or if none exists
      translationLanguage: "en" | "de" | null; // "en" when shown because no German exists
      url: string;
    }
  | {
      kind: "scholar";
      key: string; // "S<uuid>"
      scholarId: string;
      scholarName: string; // in the answer language
      title: string | null; // the fatwa's question or heading
      reference: string; // printed source or site reference
      arabic: string; // the scholar's own words, unchanged (short quote)
      url: string;
    };

export type Answer = {
  language: Locale;
  claims: Claim[];
  evidence: Evidence[];
  sourceOnly?: boolean;
  attribution: { text: string; url: string };
  hadithAttribution?: { text: string; url: string }; // present when a hadith is shown
  videos?: VideoSuggestion[]; // related clips from approved channels; never evidence
  model: string;
  verifier: string;
};

export type AskResult =
  | { status: "answer"; answer: Answer }
  | { status: "no_source"; language: Locale }
  | { status: "ask_scholar"; language: Locale }
  | { status: "out_of_scope"; language: Locale };

export type PipelineDeps = {
  writer: AIProvider; // understands the question and drafts the answer
  verifier: AIProvider; // a different model that screens each claim
  search: (queries: string[], limit: number) => Promise<string[]>; // verse keys, best first
  getVerse: (key: string) => Promise<Verse | undefined>;
  neighbours: (key: string) => Promise<Verse[]>;
  // Optional second source: Sahih al-Bukhari / Sahih Muslim hadith, searched per language.
  searchHadith?: (queries: Partial<Record<Locale, string[]>>) => Promise<Hadith[]>;
  hadithTimeoutMs?: number;
  // Optional third source: short quotes of approved scholars, searched with Arabic phrases.
  searchScholars?: (arabicPhrases: string[]) => Promise<ScholarQuote[]>;
  // Optional: related videos from the approved YouTube channels, matched by title. Shown under a
  // finished answer only, never given to the models and never used as evidence.
  searchVideos?: (arabicPhrases: string[]) => Promise<VideoSuggestion[]>;
  deadlineMs?: number;
  onRefuse?: (reason: string) => void; // reason codes only, never the question
  onStep?: (step: string, elapsedMs: number) => void; // step names and timings only, for local debugging
};

