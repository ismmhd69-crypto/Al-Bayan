  const tail_start = tailMarker ? getTailSlice(t, tailMarker) : undefined;
  const mark: HadithMark = {
    id: item.id,
    url: item.url,
    start,
    kind,
    tail_start,
  };
  const val = validateSingleMark(mark, t);
  if (!val.valid) {
    console.error(`Validation failed for [${item.url}]: ${val.error}`);
    hasError = true;
  }
  marks.push(mark);
