// Read-only: measures the display split over every stored hadith and writes docs/hadith-split-samples.md
// (distribution, 40 random splits, and a list of "prophet" labels that need a second look).
// Run: npx tsx scripts/hadith-split-samples.ts
import { createClient } from "@supabase/supabase-js";
import fs from "node:fs";
import { normalizeArabic } from "../lib/ask/checks";
import { analyseHadithSplit, tailHasWords, type HadithSplitReason } from "../lib/sources/hadith-split";
import { cleanHadithMarkup } from "../lib/sources/hadith-markup";

process.loadEnvFile(".env");

type Row = { id: string; url: string; title: string | null; text_original: string };

export async function loadHadithRows(): Promise<Row[]> {
  const db = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.SUPABASE_SECRET_KEY!, { auth: { persistSession: false } });
  const rows: Row[] = [];
  for (let from = 0; ; from += 1000) {
    const { data, error } = await db.from("sources").select("id, url, title, text_original")
      .eq("kind", "hadith").order("url").range(from, from + 999);
    if (error) throw new Error(error.message);
    rows.push(...((data as Row[] | null) ?? []));
    if (!data || data.length < 1000) break;
  }
  return rows;
}

// Small seeded random generator, so the 40 samples are the same on every run.
function random(seed: number) {
  return () => {
    seed = (seed * 1664525 + 1013904223) % 4294967296;
    return seed / 4294967296;
  };
}

const lead = (chain: string) => normalizeArabic(chain).replace(/[^ء-ي\s]/g, " ").replace(/\s+/g, " ").trim();
const NAME = /(النبي|رسول الله|نبي الله|ابو القاسم|ابا القاسم)/g;

// A "prophet" label is suspicious when, after the last mention of the Prophet, the lead-in names someone
// else with "عن <name>" before the verb.
function suspicious(chain: string): boolean {
  const text = lead(chain);
  const matches = [...text.matchAll(NAME)];
  const after = matches.length ? text.slice(matches[matches.length - 1].index! + matches[matches.length - 1][0].length) : text;
  return /(^| )عن [^ ]+/.test(after);
}

async function main() {
  const rows = await loadHadithRows();
  const reasons = new Map<HadithSplitReason, number>();
  const split: { row: Row; chain: string; words: string; speaker: string; tail: boolean }[] = [];
  for (const row of rows) {
    const r = analyseHadithSplit(row.text_original);
    if (r.split) split.push({ row, chain: r.split.chain, words: r.split.words, speaker: r.split.speaker, tail: tailHasWords(r.split.tail) });
    else reasons.set(r.reason, (reasons.get(r.reason) ?? 0) + 1);
  }
  const prophet = split.filter((s) => s.speaker === "prophet");
  const other = split.filter((s) => s.speaker === "other");
  const pct = (n: number) => `${((100 * n) / rows.length).toFixed(1)}%`;
  const rand = random(20261002);
  const pool = [...split];
  const samples = Array.from({ length: Math.min(40, pool.length) }, () => pool.splice(Math.floor(rand() * pool.length), 1)[0]);
  const flagged = prophet.filter((s) => suspicious(s.chain));
  const clip = (s: string, n: number) => (s.trim().length > n ? `${s.trim().slice(0, n)}…` : s.trim()).replace(/\|/g, "/").replace(/\s+/g, " ");

  const md = [
    "# Hadith split: samples for review",
    "",
    `Generated by \`scripts/hadith-split-samples.ts\` (read-only) on ${new Date().toISOString().slice(0, 10)}. Rules: \`lib/sources/hadith-split.ts\`.`,
    "",
    "## Distribution over all stored hadith",
    "",
    "| Result | Count | Share |",
    "|---|---:|---:|",
    `| All hadith | ${rows.length} | 100% |`,
    `| Split, label "The Prophet ﷺ said" | ${prophet.length} | ${pct(prophet.length)} |`,
    `| Split, neutral label "The text of the hadith" | ${other.length} | ${pct(other.length)} |`,
    `| (of the splits: narration goes on after the quote, shown below the box) | ${split.filter((s) => s.tail).length} | ${pct(split.filter((s) => s.tail).length)} |`,
    ...[...reasons.entries()].sort((a, b) => b[1] - a[1]).map(([reason, n]) => `| Not split: ${reason} | ${n} | ${pct(n)} |`),
    "",
    "Reasons: no_quote = no quoted words (stories, descriptions); several_quotes = more than one quoted segment (dialogues); stray_quote = extra quote marks outside the Sunnah.com pattern; continuation = \"same chain / like it\" report (already left out of Ask); refers_to_other_hadith = the quote is an addition to or the meaning of another report; markup_crosses_quote = a [quran] tag with its verse would be cut by a quote mark; empty_chain / empty_words = nothing on one side; not_exact = pieces did not rejoin (should be 0).",
    "",
    `Quran markup: ${rows.filter((r) => r.text_original.includes("[quran")).length} hadith contain Sunnah.com [quran sura=..] tags. They are tidied for display only (verse kept in its braces, reference such as (6:82) added); quote marks inside the tags are not counted by the split.`,
    "",
    "## 40 random splits",
    "",
    "| # | Link | Label | Chain starts | Words |",
    "|---:|---|---|---|---|",
    ...samples.map((s, i) => `| ${i + 1} | ${s.row.url} | ${s.speaker} | ${clip(cleanHadithMarkup(s.chain), 60)} | ${clip(cleanHadithMarkup(s.words), 140)} |`),
    "",
    "## \"Prophet\" labels with \"عن <name>\" after the last mention of the Prophet",
    "",
    flagged.length === 0
      ? "None. Every \"prophet\" label has the Prophet named directly before قال / يقول (or directly after it)."
      : flagged.map((s) => `- ${s.row.url}: …${clip(s.chain.slice(-120), 120)}`).join("\n"),
    "",
  ].join("\n");
  fs.writeFileSync("docs/hadith-split-samples.md", md);
  console.log(JSON.stringify({ total: rows.length, prophet: prophet.length, other: other.length, tail: split.filter((s) => s.tail).length, reasons: Object.fromEntries(reasons), flagged: flagged.length }));
}

if (process.argv[1]?.endsWith("hadith-split-samples.ts")) main().catch((e) => { console.error(e); process.exit(1); });
